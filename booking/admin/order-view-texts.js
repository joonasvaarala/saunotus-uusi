let db = new Map();
let loaded = false;

export function fillOvText(text, vars) {
  return String(text ?? '').replace(/\{\{var:([a-z0-9_]+)\}\}/g, (_, k) => (vars && vars[k] != null ? String(vars[k]) : ''));
}

function applyLive(raw, vars) {
  for (const m of String(raw).matchAll(/\{\{([^{}]*)\}\}/g)) {
    const name = /^var:([a-z0-9_]+)$/.exec(m[1]);
    if (!name || vars?.[name[1]] == null) return null;
  }
  const out = fillOvText(raw, vars);
  return /\{\{|\}\}|</.test(out) ? null : out;
}

export function primeOvTexts(rows) {
  if (!Array.isArray(rows)) return false;
  const next = new Map();
  for (const r of rows) {
    if (!r || typeof r.key !== 'string' || !PREFIXES.some((p) => r.key.startsWith(p))) continue;
    if (r.lang !== 'fi' && r.lang !== 'en') continue;
    if (typeof r.text !== 'string' || !r.text.trim()) continue;
    next.set(`${r.key}|${r.lang}`, r.text);
  }
  db = next;
  loaded = true;
  return true;
}

export async function loadOvTexts(rpcFn) {
  if (loaded) return true;
  if (typeof rpcFn !== 'function') return false;
  try {
    const t = await getSiteTexts(rpcFn);
    if (!t || t.ok !== true || !Array.isArray(t.texts)) return false;
    return primeOvTexts(t.texts);
  } catch {
    return false;
  }
}

export function clearOvTextCache() { db = new Map(); loaded = false; }

/** Täysi avain (ui.admin.…). */
export function ovTextFull(key, vars, lang = getLang()) {
  const live = db.get(`${key}|${lang}`);
  const filled = live != null ? applyLive(live, vars) : null;
  if (filled != null) return filled;
  const raw = ORDER_VIEW_TEXTS[lang]?.[key] ?? ORDER_VIEW_TEXTS.fi[key] ?? key;
  return vars ? fillOvText(raw, vars) : raw;
}

