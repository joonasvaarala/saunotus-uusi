let db = new Map(), loaded = false;
export function _resetEventsTexts() { db = new Map(); loaded = false; }
/** Tietokannan tekstit (public_get_site_texts); virhe → sanakirja. */
export async function loadEventsTexts(rpcFn) {
  if (loaded) return true;
  if (typeof rpcFn !== 'function') return false;
  try {
    const t = await rpcFn('public_get_site_texts', { p_lang: null });
    if (!t || t.ok !== true || !Array.isArray(t.texts)) return false;
    const next = new Map();
    for (const r of t.texts) {
      if (!r || typeof r.key !== 'string' || !PREFIXES.some((p) => r.key.startsWith(p))) continue;
      if (r.lang !== 'fi' && r.lang !== 'en') continue;
      if (typeof r.text !== 'string' || !r.text.trim()) continue;
      next.set(`${r.key}|${r.lang}`, r.text);
    }
    db = next; loaded = true; return true;
  } catch { return false; }
}
/** Teksti avaimella (lyhyt muoto 'title' = ui.admin.events.title). vars täyttää {{var:nimi}}; puuttuva arvo → tyhjä. */
export function evText(key, vars = null, lang = getLang()) {
  const k = key.startsWith('ui.') ? key : E + key;
  const L = lang === 'en' ? 'en' : 'fi';
  let s = db.get(`${k}|${L}`) ?? EVENTS_TEXTS[L][k] ?? EVENTS_TEXTS.fi[k] ?? k;
  if (vars) s = s.replace(/\{\{var:([a-z_]+)\}\}/g, (_, n) => (vars[n] == null ? '' : String(vars[n])));
  return s;
}
